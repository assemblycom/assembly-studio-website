// The whole interactive section: a vertical tab list on the left whose active
// step both reveals its callout copy and lights up the matching region in the
// mock on the right. It auto-advances through the three regions and loops;
// clicking or hovering a tab (or a region in the mock) jumps the tour there.
// Progress is painted imperatively (refs) so the loop never re-renders the mock.
function ProductionGapExplorer() {
  const [active, setActive] = useState(0);

  // Refs so the rAF loop reads state without re-subscribing, and the per-tab
  // progress rails can be painted directly (no per-frame React render).
  const activeRef = useRef(0);
  const progressRef = useRef(0);
  const fillRefs = useRef<(HTMLSpanElement | null)[]>([]);
  const rootRef = useRef<HTMLDivElement>(null);
  const onScreenRef = useRef(true);

  useEffect(() => {
    activeRef.current = active;
  }, [active]);

  const paint = () => {
    fillRefs.current.forEach((el, idx) => {
      if (!el) return;
      const p = idx === activeRef.current ? progressRef.current : 0;
      el.style.transform = `scaleX(${p})`;
    });
  };

  // Jump to a step and restart its dwell.
  const activate = (i: number) => {
    activeRef.current = i;
    progressRef.current = 0;
    paint();
    setActive(i);
  };
  const activateId = (id: RegionId) =>
    activate(REGIONS.findIndex((r) => r.id === id));

  useEffect(() => {
    const reduce = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
    if (reduce) return; // no auto-advance; tabs still switch on click

    // Only run the clock while the section is on screen — browsers throttle rAF
    // offscreen, which would desync the progress rail (same fix as How it works).
    const el = rootRef.current;
    let io: IntersectionObserver | undefined;
    if (el && "IntersectionObserver" in window) {
      io = new IntersectionObserver(
        ([entry]) => {
          onScreenRef.current = entry.isIntersecting;
        },
        { threshold: 0 },
      );
      io.observe(el);
    }

    let raf = 0;
    let last = 0;
    const tick = (ts: number) => {
      const running = onScreenRef.current && !document.hidden;
      if (!running) {
        last = 0; // resume with a fresh delta instead of one big leap
      } else {
        if (!last) last = ts;
        const dt = Math.min(ts - last, 64); // clamp throttled gaps
        last = ts;
        progressRef.current += dt / DWELL_MS;
        if (progressRef.current >= 1) {
          progressRef.current = 0;
          const next = (activeRef.current + 1) % REGIONS.length;
          activeRef.current = next;
          setActive(next);
        }
      }
      paint();
      raf = requestAnimationFrame(tick);
    };
    raf = requestAnimationFrame(tick);
    return () => {
      cancelAnimationFrame(raf);
      io?.disconnect();
    };
  }, []);

  return (
    <div
      ref={rootRef}
      // No frame, fill, or column divider — the tab hairlines and the blue
      // visual carry the structure on their own. The column gap matches the
      // section header's, since there's no longer a divider to sit between them.
      className="grid md:grid-cols-[minmax(0,330px)_minmax(0,1fr)] md:items-stretch md:gap-x-12"
    >
      {/* Left — vertical tabs; the active one expands its copy. */}
      <div
        role="tablist"
        aria-orientation="vertical"
        aria-label="What ships with every app"
        className="order-2 flex flex-col pb-5 md:order-none md:pb-6"
      >
        {REGIONS.map((r, i) => {
          const on = i === active;
          return (
            <button
              key={r.id}
              type="button"
              role="tab"
              aria-selected={on}
              // Click (or keyboard focus) only — on hover, the panel changed
              // under the pointer on the way past it, which reads as the page
              // twitching rather than as a control being used. The autoplay
              // still advances it on its own.
              onClick={() => activate(i)}
              onFocus={() => activate(i)}
              // No horizontal inset: with the frame gone the copy aligns to the
              // section heading above instead of sitting inside a phantom edge.
              className="group relative border-t border-border py-5 pr-5 text-left outline-none first:border-t-0 focus-visible:bg-foreground/[0.03] md:pr-8 [[data-theme=dark]_&]:border-white/15"
            >
              {/* Top-edge rail that fills left→right over the dwell on the
                  active tab. -top-px, not top-0: absolute offsets resolve against
                  the padding box, which begins inside the 1px border-t, so top-0
                  parked the fill one pixel BELOW the gray hairline instead of
                  covering it. */}
              <span
                aria-hidden
                className="absolute inset-x-0 -top-px z-10 h-px overflow-hidden group-first:top-0"
              >
                <span
                  ref={(el) => {
                    fillRefs.current[i] = el;
                  }}
                  className="block h-full w-full origin-left bg-foreground"
                  style={{ transform: "scaleX(0)" }}
                />
              </span>

              <span
                className={`block [font-family:var(--font-diatype-mono)] text-[11px] uppercase tracking-[0.08em] ${
                  on ? "text-muted-foreground" : "text-muted-foreground/50"
                }`}
              >
                {r.tag}
              </span>

              <p
                className={`mt-1.5 text-[17px] leading-snug transition-colors ${
                  on ? "text-foreground" : "text-muted-foreground group-hover:text-foreground"
                }`}
              >
                {r.header}
              </p>

              {/* Body — revealed only for the active step (smooth height). */}
              <div
                className={`grid transition-all duration-300 ease-out ${
                  on ? "mt-2 grid-rows-[1fr] opacity-100" : "grid-rows-[0fr] opacity-0"
                }`}
              >
                <p className="overflow-hidden text-pretty text-sm leading-relaxed text-muted-foreground">
                  {r.body}
                </p>
              </div>
            </button>
          );
        })}
      </div>

      {/* The brand-blue box, rounded on every side. It has no right padding, so
          the app content runs to the box's right edge and cuts off there; the
          browser chrome (URL + avatar) spans the full width, so the top-right
          avatar stays in view even though the table bleeds off.
          On mobile it leads (the step list below reads as its legend) and the
          mock is laid out at a desktop width and scaled down to fit, rather than
          squeezed into a phone column where the sidebar and table would collapse
          into unreadable slivers. */}
      {/* min-w-0: the mock's sidebar and table have hard minimums (~750px), so
          without it the grid item takes the mock's min-content width and the
          blue box runs off the phone's right edge instead of ending at the
          section gutter. */}
      <div className="order-1 mb-8 flex min-w-0 self-stretch md:order-none md:mb-0">
        {/* Hairline below md only: the mock is laid out at desktop width and
            clipped by this box, so at phone widths its white surface reaches
            the box's right edge and meets the white page with nothing between
            them. From md up the box has room to show blue on every side. */}
        <div className="h-[320px] w-full min-w-0 overflow-hidden rounded-xl bg-[#7DA4FF] py-4 pl-4 ring-1 ring-black/[0.08] md:h-auto md:py-7 md:pl-7 md:ring-0">
          {/* The mock is a desktop layout — the sidebar and the table are
              percentages of a wide viewport, so at phone width they collapse
              into each other. It's laid out at a desktop width and cropped by
              the box instead, the same right-edge crop the design already uses
              on desktop, and the box is height-capped so it reads as a landscape
              window rather than a tall column. */}
          <div className="w-[760px] md:w-auto">
            <ProductionGapVisual active={REGIONS[active].id} setActive={activateId} />
          </div>
        </div>
      </div>
    </div>
  );
}

